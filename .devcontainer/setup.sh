#!/usr/bin/env bash
# ─────────────────────────────────────────────────────────────────────────────
# JeshlaAutoAI — Codespaces startup helper
# Run this once after the container starts:  bash .devcontainer/setup.sh
# It builds a .env from your Codespaces secrets and shows run commands.
# ─────────────────────────────────────────────────────────────────────────────

set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
ENV_FILE="$ROOT/.env"

echo ""
echo "================================================"
echo "  JeshlaAutoAI — Codespaces Setup"
echo "================================================"

# ── 1. Write .env from secrets injected by Codespaces ────────────────────────
# Secrets set in GitHub → Settings → Secrets → Codespaces become env vars.
# We write them to .env so python-dotenv picks them up at runtime.

echo "Writing .env from Codespaces secrets..."

cat > "$ENV_FILE" <<EOF
# Auto-generated by .devcontainer/setup.sh — do not commit this file
LLM_PROVIDER=${LLM_PROVIDER:-openrouter}
GROQ_API_KEY=${GROQ_API_KEY:-}
GROQ_MODEL=${GROQ_MODEL:-llama-3.3-70b-versatile}
OPENROUTER_API_KEY=${OPENROUTER_API_KEY:-}
OPENROUTER_MODEL=${OPENROUTER_MODEL:-nvidia/nemotron-3-super-120b-a12b:free}
ANTHROPIC_API_KEY=${ANTHROPIC_API_KEY:-}
GEMINI_MODEL=${GEMINI_MODEL:-gemini-2.0-flash}
SERPAPI_KEY=${SERPAPI_KEY:-}
JIRA_SITE_URL=${JIRA_SITE_URL:-}
JIRA_PROJECT_KEY=${JIRA_PROJECT_KEY:-}
JIRA_ALLOW_CREATE=false
AI_MAX_STEPS=20
AI_MAX_CONVERSATION_CHARS=12000
OPENROUTER_CONTEXT_TOKENS=8000
OPENROUTER_OUTPUT_TOKEN_LIMIT=2048
EOF

echo "✅ .env written to $ENV_FILE"

# ── 2. Install dependencies if not already done ───────────────────────────────
if ! python -c "import langgraph" 2>/dev/null; then
  echo "Installing dependencies..."
  pip install -r "$ROOT/requirements-rag.txt" -q
  echo "✅ Dependencies installed"
else
  echo "✅ Dependencies already installed"
fi

# ── 3. Print run commands ─────────────────────────────────────────────────────
echo ""
echo "================================================"
echo "  Ready!  Choose what to run:"
echo "================================================"
echo ""
echo "  🖥️  Console agent (LangGraph — see execution live):"
echo "      python -m agent.langgraph.langgraph_agent"
echo ""
echo "  🌐  Streamlit browser UI:"
echo "      python -m streamlit run streamlit_app.py --server.address 0.0.0.0"
echo "      (Codespaces will pop up an 'Open in Browser' button for port 8501)"
echo ""
echo "  🧪  Offline tests:"
echo "      python tests/run_offline.py"
echo ""
